def armour(name, mat, part):
    """our armour masks (tools/paint_items.py), shaded by their letters, coloured from the source"""
    def gen(ctx):
        mask = {'helmet': paint_items.HELMET, 'chestplate': paint_items.CHESTPLATE,
                'leggings': paint_items.LEGGINGS, 'boots': paint_items.BOOTS}[part]
        return lettered(ctx, name, paint_items.rows(mask), ctx.px(name) or ctx.px(TOOL_MAT.get(mat, 'iron_block')))
    return gen


LEVEL = {'o': 0.0, 'd': 0.3, 'm': 0.55, 'l': 0.8, 'h': 1.0}


def lettered(ctx, name, rows_, src, extra=None):
    f, mask = [0.0] * (N * N), [False] * (N * N)
    other = {}
    for y, row in enumerate(rows_):
        for x, ch in enumerate(row):
            if ch in LEVEL:
                f[at(x, y)], mask[at(x, y)] = LEVEL[ch], True
            elif ch != '.':
                other.setdefault(ch, []).append(at(x, y))
    c = Canvas(ctx.style, name, ref=ctx.ref(name))
    c.part(f, select(src, lambda p: True), mask, flat=True)
    for ch, idx in other.items():
        col = (extra or {}).get(ch) or src
        c.part([0.5 - 0.02 * (i % N + i // N) for i in range(N * N)], col, [i in idx for i in range(N * N)])
    return c.image()


def own_mask(name, rows_fn, colour_names):
    def gen(ctx):
        src = None
        for n in colour_names:
            src = ctx.px(n)
            if src:
                break
        rows_ = rows_fn()
        extra = {'p': [(20, 8, 10, 255)], 's': select(src, lambda p: p[0] > p[2]) or src}
        return lettered(ctx, name, rows_, src, extra)
    return gen


def shape_of(px, w, h, k=5):
    """a drawing's shape: its drawn pixels (in a 16x16 frame, top left) -> part letter, the parts
    being its few main colours (tools/redraw.py k-means)"""
    import redraw
    drawn = [i for i in range(w * h) if px[i][3] > 40]
    if not drawn:
        return {}, {}
    k = max(1, min(k, len(set(px[i][:3] for i in drawn)) // 2))
    cents = redraw.kmeans([tuple(px[i]) for i in drawn], k)[0]
    cells_, cols = {}, {}
    for i in drawn:
        j = min(range(len(cents)), key=lambda c: redraw.dist2(px[i], cents[c]))
        part = 'abcdefgh'[j]
        cells_[at(i % w, i // w)] = part
        cols.setdefault(part, []).append(px[i])
    return cells_, cols


def from_shape(ctx, name, im):
    """a drawn picture painted anew in the shape it has in the colour source (our first pack): the
    same outline and parts, shaded our way (a dark outline round it, each part lit on its top left
    and shaded on its bottom right where it meets another part or the edge), its colours by rank"""
    w, h = im.size
    px = list(im.convert('RGBA').get_flattened_data())
    cells_, cols = shape_of(px, w, h)
    if not cells_:
        return None
    rnd = rng(name, 'shape')
    wn = white(rnd)
    f = {}
    for i, part in cells_.items():
        x, y = i % N, i // N

        def nb(dx, dy):
            xx, yy = x + dx, y + dy
            return cells_.get(at(xx, yy)) if 0 <= xx < N and 0 <= yy < N else None
        if any(nb(dx, dy) is None for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1))):
            v = 0.0
        else:
            v = 0.52 - 0.01 * (x + y)
            if nb(-1, 0) != part or nb(0, -1) != part:
                v += 0.28
            elif nb(1, 0) != part or nb(0, 1) != part:
                v -= 0.18
        f[i] = v + 0.06 * wn[i]
    c = Canvas(ctx.style, name, ref=ctx.ref(name))
    for part in sorted(set(cells_.values())):
        mask = [cells_.get(i) == part for i in range(N * N)]
        c.part([f.get(i, 0) for i in range(N * N)], cols[part], mask)
    out = c.image()
    alpha = {i: px[(i // N) * w + i % N][3] for i in cells_}
    res = out.load()
    for i, a in alpha.items():          # see-through drawings (cracks) keep their see-through
        if a < 250:
            r, g, b, _ = res[i % N, i // N]
            res[i % N, i // N] = (r, g, b, a)
    return out.crop((0, 0, w, h)) if (w, h) != (N, N) else out


