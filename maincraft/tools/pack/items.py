def varied(cells_):
    """the variants draw items the way Minecraft holds them (no turning): only their drawings differ"""
    return cells_
    if P(0, 1, 0):
        return {at(N - 1 - i % N, i // N): v for i, v in cells_.items()}
    if P(0, 0, 1):
        xs, ys = [i % N for i in cells_], [i // N for i in cells_]
        dx = 1 if max(xs) < N - 1 else -1 if min(xs) > 0 else 0
        dy = -1 if min(ys) > 0 else 1 if max(ys) < N - 1 else 0
        return {at(i % N + dx, i // N + dy): v for i, v in cells_.items()}
    return cells_


def masked(name, mask):
    def gen(ctx):
        cells_ = varied(grid(MASKS[mask]))
        src = ctx.px(name) or ctx.px('item_stick')
        parts = set(cells_.values())
        cols = {'a': src}
        wood_px = ctx.px('item_stick') or ctx.px('oak_planks')
        if 'h' in parts:
            cols['h'] = select(src, lambda p: not not_handle(p)) or wood_px
            cols['a'] = select(src, not_handle) or src
        if 'l' in parts:
            cols['l'] = select(src, lambda p: p[1] > p[0] + 10) or ctx.px('oak_leaves')
            cols['a'] = select(src, lambda p: not p[1] > p[0] + 10) or src
        if mask in ('bucket', 'bowl', 'stew'):
            metal = ctx.px('item_bucket') if mask == 'bucket' else ctx.px('item_bowl')
            cols['a'] = select(metal or src, lambda p: True)
            cols['c'] = cols['a']
            water = select(src, lambda p: p[2] > p[0] + 30) or [   # a bucket's water is blue (the still water is
                (q[0] * 63 // 255, q[1] * 118 // 255, q[2] * 228 // 255, q[3])   # grey until the biome tints it)
                for q in (ctx.px('water_still') or [])]
            fill = {'water_bucket': water, 'lava_bucket': ctx.px('lava_still'),
                    'mushroom_stew': select(src, lambda p: p[0] > p[2] + 30)}.get(name[5:])
            cols['b'] = fill or cols['a']
            cols['d'] = fill or cols['a']
        if mask in ('feather', 'arrow'):
            cols['b'] = cols['f'] = select(src, lambda p: lum(p) > 150) or src
            cols['h'] = wood_px
        if mask in ('bow', 'rod'):
            cols['h'] = wood_px
            cols['s'] = select(src, lambda p: lum(p) > 150) or ctx.px('white_wool')
        if mask in ('shears', 'flint_and_steel'):
            cols['a'] = select(src, lambda p: abs(p[0] - p[2]) < 20 and lum(p) > 100) or ctx.px('iron_block')
            cols['b'] = select(src, lambda p: not (abs(p[0] - p[2]) < 20 and lum(p) > 100)) or src
        if mask == 'boat':
            cols['a'] = ctx.px('oak_planks')
            cols['b'] = sorted(ctx.px('oak_planks'), key=lum)[:40]
        if mask == 'minecart':
            cols['a'] = ctx.px('iron_block')
            cols['b'] = sorted(ctx.px('iron_block'), key=lum)[:40]
            cols['c'] = sorted(ctx.px('iron_block'), key=lum)[:30]
        if mask == 'steak' or mask == 'drumstick':
            cols['b'] = select(src, lambda p: lum(p) > 170) or ctx.px('white_wool')
            cols['a'] = select(src, lambda p: lum(p) <= 170) or src
        if mask == 'slice':
            cols['b'] = select(src, lambda p: p[1] > p[0]) or ctx.px('melon_side')
            cols['a'] = select(src, lambda p: p[0] > p[1]) or src
        if mask == 'berries':
            cols['a'] = select(src, lambda p: p[0] > p[1] + 40) or src
            cols['h'] = select(src, lambda p: p[1] >= p[0]) or ctx.px('oak_leaves')
        if mask == 'egg':
            cols['b'] = sorted(src, key=lum)[:max(6, len(src) // 4)]
        return paint(ctx, name, cells_, cols)
    return gen


