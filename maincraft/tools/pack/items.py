def slot(part):
    """the empty armour slot marks: the armour's outline, faint"""
    def gen(ctx):
        mask = {'helmet': paint_items.HELMET, 'chestplate': paint_items.CHESTPLATE,
                'leggings': paint_items.LEGGINGS, 'boots': paint_items.BOOTS}[part]
        rows_ = paint_items.rows(mask)
        from PIL import Image
        im = Image.new('RGBA', (N, N))
        for y, row in enumerate(rows_):
            for x, ch in enumerate(row):
                if ch != '.':
                    v = 70 if ch == 'o' else 110
                    im.putpixel((x, y), (v, v, v, 170))
        return im
    return gen


