"""Items: tools, weapons, armour, ingots and gems, food, buckets, dyes, beds and the rest.

Each item is an outline drawing of parts. A shape is either drawn by a function (tools along the
diagonal) or written as a mask of letters: '.' empty; a, b, c: parts shaded automatically (dark
outline where the shape ends, light on the top left, shade on the bottom right). Each part takes
its colours from the source item's pixels that belong to it (a test per part), by rank.
"""
