def grid(text):
    rows = [r for r in text.strip('\n').split('\n')]
    assert len(rows) == N and all(len(r) == N for r in rows), text
    return {at(x, y): ch for y, r in enumerate(rows) for x, ch in enumerate(r) if ch != '.'}


def shade(cells_):
    """auto shading of a part drawing: outline 0, lit top-left rim, shaded bottom-right rim"""
    f = {}
    for i, part in cells_.items():
        x, y = i % N, i // N

        def has(dx, dy):
            xx, yy = x + dx, y + dy
            return 0 <= xx < N and 0 <= yy < N and (yy * N + xx) in cells_
        if not (has(1, 0) and has(-1, 0) and has(0, 1) and has(0, -1)):
            f[i] = 0.0
            continue
        v = 0.55 - 0.012 * (x + y)
        if not has(-1, -1) or not has(-2, 0) or not has(0, -2):
            v += 0.3
        if not has(1, 1) or not has(2, 0) or not has(0, 2):
            v -= 0.2
        f[i] = v
    return f


def paint(ctx, name, cells_, colours, seed=None):
    """cells_: pixel -> part letter; colours: part -> source pixels"""
    rnd = rng(name)
    f = shade(cells_)
    w = white(rnd)
    c = Canvas(ctx.style, name, ref=ctx.ref(name))
    for part in sorted(set(cells_.values())):
        mask = [cells_.get(i) == part for i in range(N * N)]
        c.part([f.get(i, 0) + 0.06 * w[i] for i in range(N * N)], colours.get(part) or colours.get('a'), mask)
    return c.image()


