def ore_plan(name):
    g = [['.'] * 16 for _ in range(16)]
    for x0, y0, shape in ORE_AT[name]:
        for dy, row in enumerate(NUGGET[shape]):
            for dx, c in enumerate(row):
                if c != '.':
                    g[(y0 + dy) % 16][(x0 + dx) % 16] = c
    return [''.join(r) for r in g]
