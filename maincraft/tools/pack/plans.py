# the lantern: the carved pumpkin's own face, lit from inside (light at the holes, brighter at their middle)
def _lit(face):
    rows = [list(r) for r in face.strip().split('\n')]
    out = []
    for y, r in enumerate(rows):
        o = ''
        for x, c in enumerate(r):
            if c == '0':
                inner = all(0 <= x + dx < 16 and 0 <= y + dy < 16 and rows[y + dy][x + dx] == '0' for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)))
                o += '4' if inner else '3'
            else:
                o += {'1': '0', '2': '1', '3': '2'}[c]
        out.append(o)
    return '\n' + '\n'.join(out)


